import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const app = readFileSync('src/App.tsx', 'utf8')
const drawer = readFileSync('src/features/map/MapDrawer.tsx', 'utf8')
const boundary = readFileSync('src/features/map/MapErrorBoundary.tsx', 'utf8')
const canvas = readFileSync('src/features/map/MapCanvas.tsx', 'utf8')
const store = readFileSync('src/features/map/mapUiStore.ts', 'utf8')
const css = readFileSync('src/index.css', 'utf8')
const { useMapUiStore } = await import('../src/features/map/mapUiStore.ts')

assert.match(app, /维斯特洛地图/)
assert.match(app, /e\.key === 'm'/i)
assert.match(drawer, /aria-label="维斯特洛地图"/)
assert.match(drawer, /地图资料未能载入/)
assert.match(drawer + boundary, /重新载入地图/)
assert.doesNotMatch(drawer + boundary, /重新载入页面|window\.location\.reload/)
assert.match(drawer, /mapRepository\.clear\(\)/)
assert.match(canvas, /new maplibregl\.Map/)
assert.match(store, /ActiveDrawer = 'map' \| 'character' \| 'asset' \| null/)
assert.doesNotMatch(drawer + store + css, /mapMode|map-mode-tabs|map-mode-empty|titleExpansion/)
assert.match(drawer, /CountyDetails/)
assert.match(drawer, /LocationDetails/)
assert.match(drawer, /map-destination-pick-notice/)
assert.match(css, /72vw/)
assert.match(css, /1180px/)
assert.match(css, /82vw/)
assert.match(css, /100vw/)

useMapUiStore.setState({ activeDrawer: null, selection: { countyId: null, locationId: null }, focusRequest: null, lastViewport: null })
useMapUiStore.getState().openMap({ kind: 'location', locationId: 'b_winterfell' })
assert.equal(useMapUiStore.getState().activeDrawer, 'map')
assert.deepEqual(useMapUiStore.getState().focusRequest?.target, { kind: 'location', locationId: 'b_winterfell' })
useMapUiStore.getState().selectLocation('c_winterfell', 'b_winterfell')
assert.deepEqual(useMapUiStore.getState().selection, { countyId: 'c_winterfell', locationId: 'b_winterfell' })
useMapUiStore.getState().clearLocation()
assert.deepEqual(useMapUiStore.getState().selection, { countyId: 'c_winterfell', locationId: null })
useMapUiStore.getState().openCharacterDrawer()
assert.equal(useMapUiStore.getState().activeDrawer, 'character')
useMapUiStore.getState().toggleMap()
assert.equal(useMapUiStore.getState().activeDrawer, 'map')
useMapUiStore.getState().closeDrawer()
assert.equal(useMapUiStore.getState().activeDrawer, null)
console.log('地图抽屉结构检查通过。')
